// Кука выбранного города: имя и атрибуты в одном месте.
//
// Отдельным leaf-модулем, а не внутри `@/server/city`: её трогает и выход из
// аккаунта, а тот живёт на клиенте. Через серверный модуль он тянул бы за собой
// auth и весь каталог — цепочку, которой в браузерном бандле делать нечего.

import { getEnv } from "@/lib/env";

export const CITY_COOKIE = "city";

// Год: выбор города — из тех настроек, которые делают один раз. httpOnly, хотя
// кука не секрет: читать её на клиенте незачем — значение доезжает туда
// провайдером из layout'а, а второй источник правды в браузере разошёлся бы с
// серверным.
export function cityCookieOptions() {
  return {
    httpOnly: true,
    sameSite: "lax" as const,
    secure: getEnv().NEXTAUTH_URL.startsWith("https://"),
    path: "/",
    maxAge: 60 * 60 * 24 * 365,
  };
}
