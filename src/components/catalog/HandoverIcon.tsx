import { ArrowLeftRight, MapPin, Truck } from "lucide-react";

// Значок способа получения — один на весь проект. Живёт здесь, а не рядом с
// каждым потребителем: раньше карточка выдачи и блок брони на странице позиции
// рисовали одно и то же свойство разными значками, и человек, перешедший из
// выдачи на позицию, видел вместо коробки грузовик.
//
// Набор из дизайн-пакета карточки: обмен — оба способа, грузовик — доставка,
// булавка — самовывоз. Булавка же достаётся случаю «ни одного способа»: место
// встречи всё равно обсуждают, и это ближе к правде, чем грузовик или пустота.
// Сам случай отличается текстом рядом, значок его не несёт.
//
// Размер и цвет задаёт вызывающий: в подвале карточки значок 15px, в блоке
// брони 16px. Цвет по умолчанию охряный — способ получения относится к
// предмету, а не к действию, и кнопкой быть не притворяется.
export function HandoverIcon({
  pickup, delivery, className = "h-4 w-4 shrink-0 text-accent",
}: {
  pickup: boolean;
  delivery: boolean;
  className?: string;
}) {
  const Icon = pickup && delivery ? ArrowLeftRight : delivery ? Truck : MapPin;
  return <Icon className={className} aria-hidden="true" />;
}
