"use client";

import { useEffect } from "react";

/* Прокрутка к началу при заходе на страницу. Нужен «Сводке»: её хаб и обложка
 * рендерятся в layout, а App Router при навигации скроллит к верху
 * изменившегося сегмента — то есть к содержимому страницы, мимо шапки.
 * Возврат из раздела в кабинет без этого приземлялся сразу на сводку. */
export function ScrollReset() {
  useEffect(() => {
    window.scrollTo(0, 0);
  }, []);
  return null;
}
